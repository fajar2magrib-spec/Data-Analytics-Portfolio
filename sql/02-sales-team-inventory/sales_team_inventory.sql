-- PART 3: ANALYSIS QUERIES

-- Q1. Sales rep performance against annual target
SELECT e.name, e.region,
       COUNT(s.sale_id)                      AS deals,
       ROUND(SUM(s.amount), 0)               AS total_sales,
       e.monthly_target * 12                 AS annual_target,
       ROUND(100.0 * SUM(s.amount) / (e.monthly_target * 12), 1) AS achievement_pct,
       CASE WHEN SUM(s.amount) >= e.monthly_target * 12        THEN 'Exceeded'
            WHEN SUM(s.amount) >= e.monthly_target * 12 * 0.9  THEN 'Near target'
            ELSE 'Below target' END          AS status
FROM employees e
LEFT JOIN sales s ON s.emp_id = e.emp_id
GROUP BY e.emp_id
ORDER BY achievement_pct DESC;

-- Q2. Rank of each rep inside their region
SELECT region, name, total_sales,
       RANK() OVER (PARTITION BY region ORDER BY total_sales DESC) AS rank_in_region
FROM (
    SELECT e.region, e.name, ROUND(SUM(s.amount), 0) AS total_sales
    FROM employees e
    JOIN sales s ON s.emp_id = e.emp_id
    GROUP BY e.emp_id
)
ORDER BY region, rank_in_region;

-- Q3. Quarterly sales with cumulative total
WITH q AS (
    SELECT 'Q' || ((CAST(strftime('%m', sale_date) AS INTEGER) + 2) / 3) AS quarter,
           SUM(amount) AS sales
    FROM sales
    GROUP BY quarter
)
SELECT quarter,
       ROUND(sales, 0) AS sales,
       ROUND(SUM(sales) OVER (ORDER BY quarter), 0) AS cumulative
FROM q
ORDER BY quarter;

-- Q4. Best-selling product in each category
WITH product_sales AS (
    SELECT p.category, p.name AS product,
           SUM(s.quantity) AS units,
           ROUND(SUM(s.amount), 0) AS revenue
    FROM sales s
    JOIN products p ON p.product_id = s.product_id
    GROUP BY p.product_id
),
ranked AS (
    SELECT *, ROW_NUMBER() OVER (PARTITION BY category ORDER BY revenue DESC) AS rn
    FROM product_sales
)
SELECT category, product, units, revenue
FROM ranked
WHERE rn = 1
ORDER BY revenue DESC;

-- Q5. Stock alert: products at or below reorder level
SELECT p.name, p.category, p.stock, p.reorder_level,
       COALESCE(SUM(s.quantity), 0) AS units_sold_last_90_days
FROM products p
LEFT JOIN sales s
       ON s.product_id = p.product_id
      AND s.sale_date >= date((SELECT MAX(sale_date) FROM sales), '-90 days')
WHERE p.stock <= p.reorder_level
GROUP BY p.product_id
ORDER BY units_sold_last_90_days DESC;

-- Q6. Sales by day of the week
SELECT CASE strftime('%w', sale_date)
            WHEN '0' THEN 'Sunday' WHEN '1' THEN 'Monday' WHEN '2' THEN 'Tuesday' WHEN '3' THEN 'Wednesday' WHEN '4' THEN 'Thursday' WHEN '5' THEN 'Friday' WHEN '6' THEN 'Saturday'
       END AS weekday,
       COUNT(*) AS deals,
       ROUND(SUM(amount), 0) AS sales
FROM sales
GROUP BY strftime('%w', sale_date)
ORDER BY strftime('%w', sale_date);

-- Q7. Products that were never sold
SELECT p.product_id, p.name, p.category, p.stock
FROM products p
WHERE NOT EXISTS (
    SELECT 1 FROM sales s WHERE s.product_id = p.product_id
);
